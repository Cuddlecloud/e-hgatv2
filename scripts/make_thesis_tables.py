def small_set_table() -> str:
    """All 35 published small instances at their native fleet ratios, ten seeds each.

    The 540-replicate sweep varies A/Q on six instances. This campaign holds each instance at
    the ratio its published configuration specifies and covers the whole set, so it corroborates
    the ratio dependence on 35 instances rather than 6. Its ratios span 0.33 to 1.00 and
    therefore probe only the sub-threshold side of the effect.
    """
    import math, statistics as st, collections
    rows = json.loads(_check(Path("experiments/thesis/thesis_L_scaled.json")).read_text())
    rows = rows["per_seed"] if isinstance(rows, dict) and "per_seed" in rows else rows

    by, excluded = collections.defaultdict(list), 0
    insts = set()
    for r in rows:
        e = r["behaviour"]["exact"]
        insts.add(r["instance"])
        if not e.get("decomposition_closes") or math.isnan(e["migration"]):
            excluded += 1
            continue
        by[round(r["agv_per_qc"], 3)].append(e["migration"])

    lines = [
        r"% Generated by scripts/make_thesis_tables.py -- do not edit by hand.",
        r"\begin{table}[tb]", r"\centering", r"\small",
        r"\caption[Migration on the published small instances at their native ratios]{Migration "
        r"on all " + str(len(insts)) + r" published small instances at their "
        r"native fleet ratios, ten seeds each, grouped by ratio. This campaign is independent of "
        r"the sweep of Table~\ref{tab:migration}, which varies the ratio on six instances; here "
        r"the ratio is whatever the published configuration specifies. The proportion of "
        r"replicates whose migration exceeds $0.1$ in magnitude rises monotonically with the "
        r"ratio, which corroborates the dependence on a larger set of instances. The ratios "
        r"reach only $1.00$, so the campaign probes the sub-threshold side alone. "
        + _closure_note(excluded, len(rows)) + r"}",
        r"\label{tab:smallset}",
        r"\footnotesize",
        r"\begin{tabular}{rrrrr}", r"\toprule",
        r"$A/Q$ & $n$ & mean migration & mean $|$migration$|$ & $|$migration$| > 0.1$ \\",
        r"\midrule",
    ]
    for aq in sorted(by):
        v = by[aq]
        big = sum(1 for x in v if abs(x) > 0.1) / len(v)
        lines.append(f"{aq:.2f} & {len(v)} & ${st.mean(v):+.3f}$ & "
                     f"{st.mean(abs(x) for x in v):.3f} & {big*100:.0f}\\% \\\\")
    allv = [x for v in by.values() for x in v]
    lines += [
        r"\midrule",
        rf"\multicolumn{{5}}{{l}}{{Overall: $n = {len(allv)}$, mean "
        rf"${st.mean(allv):+.3f}$, mean $|$migration$|$ "
        rf"{st.mean(abs(x) for x in allv):.3f}}} \\",
        r"\bottomrule", r"\end{tabular}", r"\end{table}", "",
    ]
    return "\n".join(lines)


def published_table() -> str:
    """The comparison against the published fixed-speed optima, generated rather than typed."""
    d = json.loads(_check(Path("experiments/thesis/published_validation.json")).read_text())
    S = d["summary"]
    label = {
        "scenario_n.c_max":            r"nominal, $C_{\max}$",
        "scenario_n.c_max_star":       r"nominal, $C_{\max}^{\star}$",
        "scenario_l_tilde_n.c_max":    r"lower--nominal, $C_{\max}$",
        "scenario_n_tilde_h.c_max_star": r"nominal--higher, $C_{\max}^{\star}$",
    }
    lines = [
        r"% Generated by scripts/make_thesis_tables.py -- do not edit by hand.",
        r"\begin{table}[tb]", r"\centering", r"\small",
        r"\caption[Computed fronts against the published fixed-speed optima]{The "
        r"makespan-optimal end of the computed fronts against the published "
        r"fixed-speed optima, over the 35 small instances. The present runs select among three "
        r"speeds per leg and therefore solve a less constrained problem, so the computed value "
        r"should lie at or below each published optimum; a value above one would indicate an "
        r"evaluator error or a search shortfall. The nominal--higher scenario is the nearest "
        r"comparison because it permits the highest fixed speed. "
        + str(d.get("blank_cells_skipped", 0)) + r" published cells are blank, the authors' "
        r"solver having failed to close them, and are skipped rather than imputed.}",
        r"\label{tab:published}",
        r"\footnotesize",
        r"\begin{tabular}{lrrrr}", r"\toprule",
        r"Published column & comparable & at or below & exact & mean gap (s) \\",
        r"\midrule",
    ]
    for k, lab in label.items():
        v = S[k]
        lines.append(f"{lab} & {v['n_comparable']} & {v['n_at_or_below']} & "
                     f"{v['n_exact']} & ${v['mean_gap']:+.2f}$ \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    return "\n".join(lines)


def families_table() -> str:
    """Migration by fleet ratio on all three instance families."""
    import statistics as st, collections
    CAMP = Path("experiments/front_campaign")
    fams = ("loading", "unloading", "mixed")
    data, meta = {}, {}
    for f in fams:
        rows = json.loads((CAMP / f / "front_campaign.json").read_text())["per_seed"]
        by = collections.defaultdict(list)
        for r in rows:
            if "migration" in r:
                by[round(r["agv_per_qc"], 2)].append(r["migration"])
        data[f] = by
        meta[f] = (len(rows), sum(r["n_closed"] for r in rows), sum(r["n_open"] for r in rows))
    # report the ratios every family reaches, so the columns are comparable row by row
    common = sorted(set.intersection(*[{k for k, v in data[f].items() if len(v) >= 20}
                                       for f in fams]))
    # The per-family counts belong in the caption. As a spanning footer row they formed one
    # unbreakable line that made the tabular 140pt wider than the text block.
    _prov = "Family sizes: " + "; ".join(
        f"{f} {meta[f][0]:,} replicates and {meta[f][1]:,} front points" for f in fams
    ).replace(",", "{,}") + "."
    lines = [
        r"% Generated by scripts/make_thesis_tables.py -- do not edit by hand.",
        r"\begin{table}[tb]", r"\centering", r"\small",
        r"\caption[Migration by fleet ratio on the three instance families]{Migration by "
        r"fleet-to-crane ratio on the three instance families. Loading is "
        r"Table 5 as printed; unloading is the same data with origins and destinations reversed; "
        r"mixed combines one loading with one unloading instance, following the construction "
        r"stated in the source. Each cell is the mean over all instances of that family and ten "
        r"seeds, restricted to the ratios every family attains. The threshold is reproduced "
        r"independently on all three: migration is negligible below $A/Q \approx 1$ and "
        rf"saturates near $-0.5$ above it. {_prov}}}",
        r"\label{tab:families}",
        r"\footnotesize",
        r"\begin{tabular}{rrrr}", r"\toprule",
        r"$A/Q$ & loading & unloading & mixed \\",
        r"\midrule",
    ]
    for r in common:
        cells = " & ".join(f"${st.mean(data[f][r]):+.3f}$" for f in fams)
        lines.append(f"{r:.2f} & {cells} \\\\")
    lines += [
        r"\bottomrule", r"\end{tabular}", r"\end{table}", "",
    ]
    return "\n".join(lines)



def validation_table() -> str:
    """Reconstructed families against the optima the source publishes for them.

    Both the unloading and the mixed families are reconstructions: the first reverses the
    origins and destinations of Table 5, the second combines pairs named in Table 3. Neither can
    be checked from inside this project, so both are compared against the published MILP optima.
    A front computed on a correctly reconstructed instance cannot beat a proven optimum by more
    than the enlarged decision space allows, and should reproduce the energy optimum outright
    wherever the speed selection does not help.
    """
    import statistics as _st
    tab = json.loads(Path("data/Container_Transport_Parsed_Tables/"
                          "container_transport_tables_1_to_5.json").read_text())["tables"]
    rows_out = []
    for fam, path, key in (("unloading", "validate_unloading", "table_2"),
                           ("mixed", "validate_mixed", "table_3")):
        f = Path(f"experiments/thesis/{path}.json")
        if not f.exists():
            continue
        d = json.loads(f.read_text())
        if key == "table_2":
            pub = {}
            for r in tab["table_2"]["rows"]:
                ln = r.get("scenario_l_tilde_n") or {}
                nh = r.get("scenario_n_tilde_h") or {}
                pub[f"U_L{r['instance'][1:]}"] = (nh.get("c_max_star"), ln.get("energy_star"))
        else:
            pub = {r["instance"]: (r["dual_cycling"].get("c_max_star"),
                                   r["dual_cycling"].get("energy_star"))
                   for r in tab["table_3"]["rows"]}
        rc, re_, ex, n_e = [], [], 0, 0
        for x in d["rows"]:
            pc, pe = pub.get(x["instance"], (None, None))
            if pc:
                rc.append(x["cmax_min"] / pc)
            if pe:
                re_.append(x["energy_min"] / pe); n_e += 1
                if abs(x["energy_min"] - pe) <= 1.0:
                    ex += 1
        rows_out.append((fam, len(d["rows"]), len(rc), _st.mean(rc), min(rc), max(rc),
                         n_e, _st.mean(re_), ex))

    lines = [
        r"% Generated by scripts/make_thesis_tables.py -- do not edit by hand.",
        r"\begin{table}[tb]", r"\centering", r"\small",
        r"\caption[Reconstructed families against the published optima]{The two reconstructed "
        r"instance families against the mixed-integer optima published for them, at the "
        r"published fleet size of two vehicles. The unloading family reverses the origins and "
        r"destinations of Table~5; the mixed family combines the pairs named in the ``comb.\ of'' "
        r"column of Table~3, and is the 26-instance small set, not the ten large dual-cycling "
        r"instances of Table~\ref{tab:dl}. "
        r"Ratios below one are expected, since the runs here select among three speeds per leg "
        r"where the published optima fix one, so they solve a less constrained problem. The "
        r"final column counts instances whose energy optimum is reproduced exactly, which the "
        r"speed selection cannot improve upon and which therefore tests the reconstruction "
        r"directly.}",
        r"\label{tab:validation}",
        r"\footnotesize",
        r"\begin{tabular}{lrrrrr}", r"\toprule",
        r"Family & instances & \multicolumn{2}{c}{$C_{\max}$ ratio} & $E$ ratio & $E$ exact \\",
        r"\cmidrule(lr){3-4}\cmidrule(lr){5-5}\cmidrule(l){6-6}",
        r" & & mean & range & mean & \\",
        r"\midrule",
    ]
    for fam, n, nc, mc, lo, hi, ne, me, ex in rows_out:
        lines.append(f"{fam} & {n} & {mc:.3f} & {lo:.3f}--{hi:.3f} & {me:.3f} & "
                     f"{ex}/{ne} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    return "\n".join(lines)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for name, fn in (
        ("migration", migration_table),
        ("dl", dl_table),
        ("traversal", traversal_table),
        ("calibration", calibration_table),
        ("smallset", small_set_table),
        ("published", published_table),
        ("families", families_table),
        ("validation", validation_table),
    ):
        try:
            (OUT / f"{name}.tex").write_text(fn())
            print(f"wrote {OUT / f'{name}.tex'}")
        except Exception as exc:
            print(f"SKIPPED {name}: {type(exc).__name__}: {exc}")


if __name__ == "__main__":
    main()
