def migration_table() -> str:
    """Compact instance-by-fleet-size matrix of migration.

    The earlier form listed all 54 cells as rows with their test statistics beside them, which
    ran to two pages and obscured the pattern it was reporting. The matrix places instances
    down and fleet sizes across, so the threshold is read directly: values are near zero to the
    left of $A/Q \\approx 1$ and saturate to the right of it. Cells not significant after Holm
    correction are parenthesised; the test statistics themselves are summarised in the text,
    being identical to three decimal places across almost every significant cell.
    """
    d = json.loads(_check(Path("experiments/thesis/migration_stats.json")).read_text())["instances"]
    # every instance is swept over nine fleet sizes, but the ratios differ per instance because
    # the crane count does; the column index is the fleet size, which is common to all.
    ncol = max(len(v) for v in d.values())
    lines = [
        r"% Generated by scripts/make_thesis_tables.py -- do not edit by hand.",
        r"\begin{table}[tb]", r"\centering", r"\small",
        r"\caption[Bottleneck migration across the fleet-to-crane ratio]{Bottleneck migration "
        r"across the fleet size, for the six swept instances. Migration is the signed shift of "
        r"the duration-weighted transport share, $\rho_{\mathrm{mk}} - \rho_{\mathrm{en}}$, on "
        r"the exact critical path, each cell the mean over ten seeds. Beneath each cell the model's "
        r"own migration is given, and beneath that the ratio $A/Q$ followed by the mean "
        r"absolute difference $|\\Delta\\rho|$ between the two. The ratio differs between "
        r"instances because the crane count does. "
        r"Parenthesised cells are those not significant at $\alpha = 0.05$ under a one-sample "
        r"Wilcoxon signed-rank test against zero, Holm-corrected within each instance's nine "
        r"fleet sizes. Migration is negligible left of $A/Q \approx 1$ and saturates to its "
        r"right.}",
        r"\label{tab:migration}",
        r"\footnotesize",
        r"\setlength{\tabcolsep}{4pt}",
        r"\begin{tabular}{l" + "r" * ncol + "}", r"\toprule",
        r"Instance & \multicolumn{" + str(ncol) + r"}{c}{fleet size $A$, with $A/Q$ beneath} \\",
        r"\cmidrule(l){2-" + str(ncol + 1) + "}",
        " & ".join([""] + [str(i + 1) for i in range(ncol)]) + r" \\",
        r"\midrule",
    ]
    for inst, cells in d.items():
        vals, model, ratios = [], [], []
        for c in cells:
            v = f"${c['mean']:+.3f}$"
            vals.append(v if c.get("significant") else f"({v})")
            # the surrogate's own migration on the same cell, and its error against the exact
            # value: this is the quantity the learned model contributes to the headline result
            mm = c.get("model_mean")
            err = c.get("rho_abs_err")
            model.append(f"\\tiny ${mm:+.3f}$" if mm is not None else "")
            ratios.append(f"\\tiny {c['aq']:.2f}" + (f", {err:.3f}" if err is not None else ""))
        for lst in (vals, model, ratios):
            lst += [""] * (ncol - len(lst))
        lines.append(f"{inst} & " + " & ".join(vals) + r" \\")
        lines.append(r"\hspace{1.2em}\tiny model & " + " & ".join(model) + r" \\")
        lines.append(" & " + " & ".join(ratios) + r" \\[1.5pt]")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    return "\n".join(lines)



_SUPERSEDED = ("thesis_DL_full.json", "thesis_L_full.json")
# published_validation.json is derived; scripts/build_published_validation.py
# regenerates it from the current campaign and refuses a superseded input.


def _check(path: Path) -> Path:
    """Refuse to read an artifact that a later run has replaced.

    Superseded files are moved to experiments/superseded/ with a reason recorded inside them.
    Reading one silently is how a starved-model number reached a table once already, so this
    raises instead of warning.
    """
    if path.name in _SUPERSEDED:
        raise SystemExit(f"REFUSING to read superseded artifact {path.name}; see "
                         f"experiments/superseded/ for why and what replaced it")
    _check_not_stale(path)
    return path


def _check_not_stale(path: Path) -> None:
    """Refuse a derived artifact older than the campaign it was computed from.

    published_validation.json is computed from a campaign rather than being a campaign output.
    When the small set was re-run it kept the previous fronts, thirteen of thirty-five best
    makespans had moved, and Table 4.1 reported a comparison against fronts the document no
    longer contained -- for a while, undetected, because nothing related the two files. Any
    artifact naming its input in "runs" or "source" is now required to be newer than it.
    """
    try:
        doc = json.loads(path.read_text())
    except (OSError, ValueError):
        return
    if not isinstance(doc, dict):
        return
    src = doc.get("runs") or doc.get("source")
    if not isinstance(src, str):
        return
    src_path = Path(src)
    if not src_path.exists():
        raise SystemExit(f"{path.name} was derived from {src}, which no longer exists; "
                         f"regenerate it before building tables")
    if src_path.stat().st_mtime > path.stat().st_mtime:
        raise SystemExit(f"{path.name} is older than {src} it was derived from; "
                         f"regenerate it before building tables")

def _closure_note(excluded: int, total: int) -> str:
    """Caption clause recording how the decomposition check fell out for a table.

    Stated positively when every replicate closes, which is the case after the terminal-reduction
    correction of Chapter~\\ref{sec:limitations}; the excluding form is retained so the caption
    remains accurate if the table is ever regenerated from data that predates it.
    """
    if excluded == 0:
        return (rf"The decomposition closes on all {total} replicates, so none is excluded.")
    return (rf"{excluded} of the {total} replicates are excluded because the decomposition does "
            r"not close, for the reason given in Chapter~\ref{sec:limitations}.")


def dl_table() -> str:
    """The published large set, over ten seeds per instance.

    Previously this table was rendered from a single exact-explanation run per instance while
    the migration table reported ten-seed means, so the two results tables did not share a
    protocol. Both now use ten seeds. Replicates whose decomposition does not close carry an
    undefined share and are excluded and counted, as in Section 5.
    """
    import math, statistics as st
    # the scaled-budget run: the earlier file trained the fused head on a constant 1200 samples
    # regardless of instance size, which is under four samples per leg at N=160 and measured a
    # starved model rather than the architecture
    _dl = _check(Path("experiments/thesis/thesis_dl_scaled.json"))
    if not _dl.exists():
        _dl = Path("experiments/thesis/thesis_DL_full.json")
    rows = json.loads(_dl.read_text())
    rows = rows["per_seed"] if isinstance(rows, dict) and "per_seed" in rows else rows

    per, excluded = {}, 0
    for r in rows:
        e = r["behaviour"]["exact"]
        if not e.get("decomposition_closes") or math.isnan(e["migration"]):
            excluded += 1
            continue
        m = r["behaviour"].get("model") or {}
        fa = r.get("faithfulness") or {}
        per.setdefault(r["instance"], []).append(
            (e["rho_makespan_end"], e["rho_energy_end"], e["migration"],
             r["num_tasks"], r["agv_per_qc"], r["behaviour"].get("n_front", 0),
             r["quality"]["mp_brkga"]["makespan_min"],
             r["quality"]["mp_brkga"]["makespan_at_energy_min"],
             m.get("migration"), fa.get("leg_jaccard")))

    names = sorted(per, key=lambda k: per[k][0][3])
    lines = [
        r"% Generated by scripts/make_thesis_tables.py -- do not edit by hand.",
        r"\begin{table}[tb]", r"\centering", r"\small",
        r"\caption[Exact explanation of both front extremes on the dual-cycling set]{Exact "
        r"explanation of both front extremes on the ten large dual-cycling "
        r"instances, averaged over five seeds each. Every instance has $A/Q = 0.50$, and the "
        r"transport share is high at both ends, so migration is negligible throughout. "
        r"Migration is the makespan-optimal share minus the energy-optimal share, as in "
        r"Table~\ref{tab:migration}. This is the degenerate regime that motivates the sweep in "
        rf"Table~\ref{{tab:migration}}. The final two columns are the learned surrogate's own "
        rf"migration on the same fronts and the Jaccard agreement of its recovered critical leg "
        rf"set with the exact one, so the model is measured on the largest instances in the "
        rf"study rather than only on the small ones. {_closure_note(excluded, len(rows))}}}",
        r"\label{tab:dl}",
        r"\footnotesize",
        r"\begin{tabular}{lrrrrrrrrr}", r"\toprule",
        r"& & & & \multicolumn{2}{c}{exact} & \multicolumn{2}{c}{exact share} & "
        r"\multicolumn{2}{c}{surrogate} \\",
        r"\cmidrule(lr){5-6}\cmidrule(lr){7-8}\cmidrule(l){9-10}",
        r"Instance & $N$ & $A/Q$ & $n$ & $C_{\max}^{\mathrm{mk}}$ & "
        r"$C_{\max}^{\mathrm{en}}$ & $\rho_{\mathrm{mk}}$ & $\rho_{\mathrm{en}}$ & "
        r"migration & leg $J$ \\",
        r"\midrule",
    ]
    mig = []
    for k in names:
        v = per[k]
        mk = st.mean(x[0] for x in v); en = st.mean(x[1] for x in v)
        mig.append(st.mean(x[2] for x in v))
        mm = [x[8] for x in v if x[8] is not None]
        jj = [x[9] for x in v if x[9] is not None]
        lines.append(
            f"{k} & {v[0][3]} & {v[0][4]:.2f} & {len(v)} & "
            f"{st.mean(x[6] for x in v):.1f} & {st.mean(x[7] for x in v):.1f} & "
            f"{mk:.3f} & {en:.3f} & "
            + (f"${st.mean(mm):+.3f}$ & " if mm else "-- & ")
            + (f"{st.mean(jj):.3f}" if jj else "--") + " \\\\")
    lines += [
        r"\midrule",
        rf"\multicolumn{{10}}{{l}}{{Mean migration ${st.mean(mig):+.3f}$, "
        rf"mean $|$migration$|$ {st.mean(abs(x) for x in mig):.3f}}} \\",
        r"\bottomrule", r"\end{tabular}", r"\end{table}", "",
    ]
    return "\n".join(lines)


